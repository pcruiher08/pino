def text_columns(text):
    """Return the text as a list of columns; each column is a list of HEIGHT bools."""
    cols = []
    for ch in text.upper():
        glyph = FONT.get(ch, FONT[" "])
        for c in range(WIDTH):
            cols.append([glyph[r][c] == "#" for r in range(HEIGHT)])
        for _ in range(SPACING):
            cols.append([False] * HEIGHT)
    return cols
